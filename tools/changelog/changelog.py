"""The changelog of the engine: one fragment per merged engine entry, the version header and the generated CHANGELOG.md.
Standard library only, Python 3.10+. The contract is `tools/changelog/CLAUDE.md`.

    python3 <engine>/tools/changelog/changelog.py current   [--root E]
    python3 <engine>/tools/changelog/changelog.py propose   --draft FILE
    python3 <engine>/tools/changelog/changelog.py add       --draft FILE --bump minor|patch|auto [--date D] [--dry-run] [--root E]
    python3 <engine>/tools/changelog/changelog.py render    [--check] [--root E]
    python3 <engine>/tools/changelog/changelog.py check     [--root E]
"""

import argparse
import datetime
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

ENGINE_ROOT = Path(__file__).resolve().parents[2]

FRAGMENT_DIR = "changelog"
CHANGELOG_FILE = "CHANGELOG.md"
VERSION_HEADER = Path("src/Modules/BECore/Utils/EngineVersion.h")
CONTENT_VERSION_HEADER = Path("src/Modules/BECore/Config/ContentVersion.h")

EXIT_OK = 0
EXIT_REFUSED = 1  # a check failed or `add` refused: the message names the file
EXIT_ERROR = 2  # the layout is not there (no header, no draft)

MINOR = "minor"
PATCH = "patch"
AUTO = "auto"
BUMPS = (MINOR, PATCH)

SECTIONS = ("Added", "Changed", "Breaking", "Migration")
BREAKING = "Breaking"
MIGRATION = "Migration"
ADAPT_MARK = "Adapt:"

KEY_VERSION = "Version"
KEY_ENTRY = "Entry"
KEY_DATE = "Date"
KEY_BUMP = "Bump"
KEY_CONTENT_VERSION = "Content version"
KEYS = (KEY_VERSION, KEY_ENTRY, KEY_DATE, KEY_BUMP, KEY_CONTENT_VERSION)

BULLET = "- "
CONTINUATION = "  "

VERSION_RE = re.compile(r"^(\d+)\.(\d+)\.(\d+)$")
ENTRY_RE = re.compile(r"^[a-z0-9][a-z0-9-]*$")
DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
META_RE = re.compile(r"^- ([A-Za-z ]+): (.+?)\s*$")
ADAPT_RE = re.compile(rf"{ADAPT_MARK}\s*\S")
MACRO_NAMES = ("MAJOR", "MINOR", "PATCH")
CONTENT_VERSION_RE = re.compile(r"kContentVersion\s*=\s*(\d+)\s*;")

CHANGELOG_PREAMBLE = (
    "# Changelog\n\n"
    "Generated by `tools/changelog/changelog.py render` from the fragments of `changelog/`; do not edit by hand "
    "(`tools/changelog/CLAUDE.md`).\n"
)

Version = tuple[int, int, int]


class ChangelogError(Exception):
    """A refusal or a broken tree; the message is what the caller prints."""


@dataclass
class Fragment:
    title: str
    entry: str = ""
    version: Version | None = None
    date: str = ""
    bump: str = ""
    content_version: int | None = None
    sections: dict[str, list[str]] = field(default_factory=dict)

    def bullets(self, section: str) -> list[str]:
        return self.sections.get(section, [])


def version_text(version: Version) -> str:
    return ".".join(str(part) for part in version)


def parse_version(text: str) -> Version:
    match = VERSION_RE.match(text.strip())
    if not match:
        raise ChangelogError(f"not a version `MAJOR.MINOR.PATCH`: {text!r}")
    return (int(match.group(1)), int(match.group(2)), int(match.group(3)))


def bumped(version: Version, bump: str) -> Version:
    major, minor, patch = version
    if bump == MINOR:
        return (major, minor + 1, 0)
    if bump == PATCH:
        return (major, minor, patch + 1)
    raise ChangelogError(f"unknown bump {bump!r} (minor or patch)")


def parse_fragment(text: str) -> Fragment:
    """Parses a fragment or a draft (a draft has no Version and Date lines). Raises ChangelogError with the line number."""
    lines = text.splitlines()
    index = 0
    while index < len(lines) and not lines[index].strip():
        index += 1
    if index >= len(lines) or not lines[index].startswith("# ") or not lines[index][2:].strip():
        raise ChangelogError(f"line {index + 1}: the first line must be `# <entry title>`")
    fragment = Fragment(title=lines[index][2:].strip())
    section: str | None = None
    meta: dict[str, str] = {}
    for number in range(index + 1, len(lines)):
        line = lines[number]
        where = f"line {number + 1}"
        if not line.strip():
            continue
        if line.startswith("## "):
            name = line[3:].strip()
            if name not in SECTIONS:
                raise ChangelogError(f"{where}: unknown section `{name}` (one of {', '.join(SECTIONS)})")
            if name in fragment.sections:
                raise ChangelogError(f"{where}: section `{name}` twice")
            section = name
            fragment.sections[name] = []
        elif section is None:
            match = META_RE.match(line)
            if not match or match.group(1) not in KEYS:
                raise ChangelogError(f"{where}: expected `- <{' | '.join(KEYS)}>: value` before the first section, got {line!r}")
            if match.group(1) in meta:
                raise ChangelogError(f"{where}: `{match.group(1)}` twice")
            meta[match.group(1)] = match.group(2)
        elif line.startswith(BULLET):
            fragment.sections[section].append(line[len(BULLET) :].rstrip())
        elif line.startswith(CONTINUATION) and fragment.sections[section]:
            fragment.sections[section][-1] += "\n" + line[len(CONTINUATION) :].rstrip()
        else:
            raise ChangelogError(f"{where}: a line of section `{section}` must be a `- ` bullet or an indented continuation, got {line!r}")
    apply_meta(fragment, meta)
    return fragment


def apply_meta(fragment: Fragment, meta: dict[str, str]) -> None:
    if KEY_VERSION in meta:
        fragment.version = parse_version(meta[KEY_VERSION])
    fragment.entry = meta.get(KEY_ENTRY, "")
    if fragment.entry and not ENTRY_RE.match(fragment.entry):
        raise ChangelogError(f"Entry `{fragment.entry}` is not a todo id (lower-case letters, digits and `-`)")
    fragment.date = meta.get(KEY_DATE, "")
    if fragment.date:
        if not DATE_RE.match(fragment.date):
            raise ChangelogError(f"Date `{fragment.date}` is not YYYY-MM-DD")
        datetime.date.fromisoformat(fragment.date)
    fragment.bump = meta.get(KEY_BUMP, "")
    if fragment.bump and fragment.bump not in BUMPS:
        raise ChangelogError(f"Bump `{fragment.bump}` is not minor or patch")
    if KEY_CONTENT_VERSION in meta:
        if not meta[KEY_CONTENT_VERSION].isdigit():
            raise ChangelogError(f"Content version `{meta[KEY_CONTENT_VERSION]}` is not a whole number")
        fragment.content_version = int(meta[KEY_CONTENT_VERSION])


def format_bullet(bullet: str) -> str:
    first, *rest = bullet.split("\n")
    return "\n".join([BULLET + first, *(CONTINUATION + line for line in rest)])


def format_fragment(fragment: Fragment) -> str:
    """The file text; parse_fragment of it gives the same fragment."""
    meta = [(KEY_VERSION, version_text(fragment.version) if fragment.version else ""), (KEY_ENTRY, fragment.entry), (KEY_DATE, fragment.date), (KEY_BUMP, fragment.bump)]
    if fragment.content_version is not None:
        meta.append((KEY_CONTENT_VERSION, str(fragment.content_version)))
    parts = [f"# {fragment.title}\n\n" + "\n".join(f"- {key}: {value}" for key, value in meta if value) + "\n"]
    for name in SECTIONS:
        if name in fragment.sections:
            parts.append(f"## {name}\n" + "".join(format_bullet(bullet) + "\n" for bullet in fragment.sections[name]))
    return "\n".join(parts)


def validate_fragment(fragment: Fragment, *, complete: bool) -> list[str]:
    """What is wrong with a fragment (`complete`: a stored one, with Version, Entry, Date and Bump); empty when nothing."""
    problems = []
    if complete:
        for key, value in ((KEY_VERSION, fragment.version), (KEY_ENTRY, fragment.entry), (KEY_DATE, fragment.date), (KEY_BUMP, fragment.bump)):
            if not value:
                problems.append(f"missing `- {key}:` line")
    elif not fragment.entry:
        problems.append("missing `- Entry:` line")
    breaking = fragment.bullets(BREAKING)
    if breaking and fragment.bump == PATCH:
        problems.append("`Bump: patch` with a Breaking section: breaking raises MINOR")
    for bullet in breaking:
        if not ADAPT_RE.search(bullet):
            problems.append(f"Breaking bullet without `{ADAPT_MARK} <how a game follows>.`: {bullet.splitlines()[0]!r}")
    return problems


def propose_bump(fragment: Fragment) -> str:
    return MINOR if fragment.bullets(BREAKING) else PATCH


def render_changelog(fragments: list[Fragment]) -> str:
    """CHANGELOG.md: the versions newest first; one fragment is one version."""
    out = [CHANGELOG_PREAMBLE]
    for fragment in sorted(fragments, key=lambda f: f.version or (0, 0, 0), reverse=True):
        facts = [f"Entry: `{fragment.entry}`", f"Bump: {fragment.bump}"]
        if fragment.content_version is not None:
            facts.append(f"Content version: {fragment.content_version}")
        block = [f"## {version_text(fragment.version)} - {fragment.date} - {fragment.title}\n\n{'. '.join(facts)}.\n"]
        for name in SECTIONS:
            if fragment.bullets(name):
                block.append(f"### {name}\n\n" + "".join(format_bullet(bullet) + "\n" for bullet in fragment.sections[name]))
        out.append("\n".join(block))
    return "\n".join(out)


def read_version_header(root: Path) -> Version:
    path = root / VERSION_HEADER
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as error:
        raise ChangelogError(f"{path}: {error.strerror}") from error
    numbers = []
    for name in MACRO_NAMES:
        match = re.search(rf"^#define BE_ENGINE_VERSION_{name}[ \t]+(\d+)[ \t]*$", text, re.MULTILINE)
        if not match:
            raise ChangelogError(f"{path}: no line `#define BE_ENGINE_VERSION_{name} <number>`")
        numbers.append(int(match.group(1)))
    return (numbers[0], numbers[1], numbers[2])


def write_version_header(root: Path, version: Version) -> None:
    """Rewrites the three macro lines and nothing else (the line endings stay)."""
    path = root / VERSION_HEADER
    text = path.read_bytes().decode("utf-8")
    for name, number in zip(MACRO_NAMES, version):
        text, count = re.subn(rf"^(#define BE_ENGINE_VERSION_{name}[ \t]+)\d+([ \t]*)(?=\r?$)", rf"\g<1>{number}\g<2>", text, flags=re.MULTILINE)
        if count != 1:
            raise ChangelogError(f"{path}: expected one line `#define BE_ENGINE_VERSION_{name} <number>`, found {count}")
    path.write_bytes(text.encode("utf-8"))


def read_content_version(root: Path) -> int:
    path = root / CONTENT_VERSION_HEADER
    try:
        match = CONTENT_VERSION_RE.search(path.read_text(encoding="utf-8"))
    except OSError as error:
        raise ChangelogError(f"{path}: {error.strerror}") from error
    if not match:
        raise ChangelogError(f"{path}: no `kContentVersion = N;`")
    return int(match.group(1))


def fragment_paths(root: Path) -> list[Path]:
    return sorted((root / FRAGMENT_DIR).glob("*.md"))


def load_fragments(root: Path) -> tuple[list[tuple[Path, Fragment]], list[str]]:
    """Every fragment of `changelog/` and the problems of the ones that are malformed (those are left out of the list)."""
    loaded, problems = [], []
    for path in fragment_paths(root):
        shown = f"{FRAGMENT_DIR}/{path.name}"
        try:
            fragment = parse_fragment(path.read_text(encoding="utf-8"))
        except (ChangelogError, ValueError) as error:
            problems.append(f"{shown}: {error}")
            continue
        found = validate_fragment(fragment, complete=True)
        if fragment.entry and path.stem != fragment.entry:
            found.append(f"the file must be named `{fragment.entry}.md` after its Entry")
        problems.extend(f"{shown}: {problem}" for problem in found)
        loaded.append((path, fragment))
    return loaded, problems


def check_tree(root: Path) -> list[str]:
    """Every problem of the tree, each starting with the file it is about."""
    loaded, problems = load_fragments(root)
    fragments = [fragment for _, fragment in loaded if fragment.version]
    seen: dict[Version, str] = {}
    for path, fragment in loaded:
        if fragment.version is None:
            continue
        if fragment.version in seen:
            problems.append(f"{FRAGMENT_DIR}/{path.name}: version {version_text(fragment.version)} is also the version of `{seen[fragment.version]}`")
        seen.setdefault(fragment.version, path.name)
    try:
        header = read_version_header(root)
    except ChangelogError as error:
        return [*problems, str(error)]
    if not fragments:
        problems.append(f"{FRAGMENT_DIR}/: no fragment (the log starts with `baseline.md`)")
    else:
        highest = max(fragment.version for fragment in fragments)
        if highest != header:
            problems.append(f"{VERSION_HEADER}: version {version_text(header)}, but the highest fragment is {version_text(highest)}")
    problems.extend(changelog_file_problems(root, fragments))
    return problems


def changelog_file_problems(root: Path, fragments: list[Fragment]) -> list[str]:
    path = root / CHANGELOG_FILE
    if not path.is_file():
        return [f"{CHANGELOG_FILE}: missing (run `changelog.py render`)"]
    if path.read_bytes().decode("utf-8") != render_changelog(fragments):
        return [f"{CHANGELOG_FILE}: differs from the rendering of the fragments (run `changelog.py render`; never edit it by hand)"]
    return []


def highest_content_version(fragments: list[Fragment]) -> int:
    return max((f.content_version for f in fragments if f.content_version is not None), default=0)


def prepare_add(root: Path, draft: Fragment, bump: str, date: str) -> tuple[Fragment, Version]:
    """The fragment `add` would write and the new header version; raises ChangelogError for every refusal."""
    if draft.version is not None or draft.date:
        raise ChangelogError("the draft must not carry `Version` or `Date` lines: `add` decides them")
    if bump == AUTO:
        bump = propose_bump(draft)
    if bump not in BUMPS:
        raise ChangelogError(f"--bump must be minor, patch or auto, got {bump!r}")
    draft.bump = bump
    if not DATE_RE.match(date):
        raise ChangelogError(f"--date `{date}` is not YYYY-MM-DD")
    draft.date = date
    problems = validate_fragment(draft, complete=False)
    if problems:
        raise ChangelogError("; ".join(problems))
    loaded, tree_problems = load_fragments(root)
    if tree_problems:
        raise ChangelogError("the existing log is broken, `check` says how: " + tree_problems[0])
    existing = [fragment for _, fragment in loaded]
    if any(fragment.entry == draft.entry for fragment in existing) or (root / FRAGMENT_DIR / f"{draft.entry}.md").exists():
        raise ChangelogError(f"entry `{draft.entry}` already has a fragment")
    header = read_version_header(root)
    if existing:
        highest = max(fragment.version for fragment in existing)
        if highest != header:
            raise ChangelogError(f"{VERSION_HEADER} says {version_text(header)} but the highest fragment is {version_text(highest)}: fix that first")
        new_version = bumped(header, bump)
    else:
        new_version = header  # the first fragment records where the log starts, it does not move the number
    engine_content = read_content_version(root)
    known_content = highest_content_version(existing)
    if draft.content_version is None:
        if engine_content > known_content:
            raise ChangelogError(
                f"kContentVersion is {engine_content} but no fragment says it went above {known_content}: add `- Content version: {engine_content}` and a `Migration` section"
            )
    elif draft.content_version > engine_content or (existing and draft.content_version <= known_content):
        raise ChangelogError(f"`Content version: {draft.content_version}` does not fit kContentVersion {engine_content} and the log's {known_content}")
    draft.version = new_version
    return draft, new_version


def command_add(root: Path, args: argparse.Namespace) -> int:
    draft = parse_fragment(read_draft(args.draft))
    fragment, version = prepare_add(root, draft, args.bump, args.date or datetime.date.today().isoformat())
    loaded, _ = load_fragments(root)
    rendered = render_changelog([*(f for _, f in loaded), fragment])
    target = root / FRAGMENT_DIR / f"{fragment.entry}.md"
    text = format_fragment(fragment)
    if args.dry_run:
        print(f"would write {FRAGMENT_DIR}/{target.name}, set {VERSION_HEADER} to {version_text(version)} and regenerate {CHANGELOG_FILE}:\n")
        print(text, end="")
        return EXIT_OK
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(text.encode("utf-8"))
    write_version_header(root, version)
    (root / CHANGELOG_FILE).write_bytes(rendered.encode("utf-8"))
    print(f"{version_text(version)}: wrote {FRAGMENT_DIR}/{target.name}, {VERSION_HEADER}, {CHANGELOG_FILE}")
    return EXIT_OK


def read_draft(path: str) -> str:
    try:
        return Path(path).read_text(encoding="utf-8")
    except OSError as error:
        raise ChangelogError(f"{path}: {error.strerror}") from error


def command_render(root: Path, args: argparse.Namespace) -> int:
    loaded, problems = load_fragments(root)
    if problems:
        for problem in problems:
            print(problem, file=sys.stderr)
        return EXIT_REFUSED
    rendered = render_changelog([fragment for _, fragment in loaded])
    path = root / CHANGELOG_FILE
    current = path.read_bytes().decode("utf-8") if path.is_file() else None
    if args.check:
        if current != rendered:
            print(f"{CHANGELOG_FILE}: out of date (run `changelog.py render`)", file=sys.stderr)
            return EXIT_REFUSED
        return EXIT_OK
    if current != rendered:
        path.write_bytes(rendered.encode("utf-8"))
    print(f"{CHANGELOG_FILE}: {len(loaded)} fragments" + ("" if current != rendered else " (unchanged)"))
    return EXIT_OK


def command_check(root: Path, args: argparse.Namespace) -> int:
    problems = check_tree(root)
    for problem in problems:
        print(problem, file=sys.stderr)
    if not problems:
        print(f"changelog ok: {version_text(read_version_header(root))}")
    return EXIT_REFUSED if problems else EXIT_OK


def command_current(root: Path, args: argparse.Namespace) -> int:
    print(version_text(read_version_header(root)))
    return EXIT_OK


def command_propose(root: Path, args: argparse.Namespace) -> int:
    print(propose_bump(parse_fragment(read_draft(args.draft))))
    return EXIT_OK


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    commands = parser.add_subparsers(dest="command", required=True)

    def command(name: str, help_text: str) -> argparse.ArgumentParser:
        sub = commands.add_parser(name, help=help_text)
        sub.add_argument("--root", default=str(ENGINE_ROOT), help="the engine folder (default: the one this tool is in)")
        return sub

    command("current", "print the version of the header")
    propose = command("propose", "print the bump a draft needs: minor with a non-empty Breaking, else patch")
    propose.add_argument("--draft", required=True)
    add = command("add", "write the fragment of a draft, bump the header, regenerate CHANGELOG.md")
    add.add_argument("--draft", required=True)
    add.add_argument("--bump", required=True, choices=[MINOR, PATCH, AUTO])
    add.add_argument("--date", help="YYYY-MM-DD (default: today)")
    add.add_argument("--dry-run", action="store_true", help="write nothing, print what would be written")
    render = command("render", "regenerate CHANGELOG.md from the fragments")
    render.add_argument("--check", action="store_true", help="write nothing, exit 1 when CHANGELOG.md is out of date")
    command("check", "exit 1 naming the file when the fragments, the header and CHANGELOG.md disagree")
    return parser


HANDLERS = {
    "current": command_current,
    "propose": command_propose,
    "add": command_add,
    "render": command_render,
    "check": command_check,
}


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        return HANDLERS[args.command](Path(args.root), args)
    except ChangelogError as error:
        print(f"changelog: {error}", file=sys.stderr)
        return EXIT_REFUSED if args.command == "add" else EXIT_ERROR


if __name__ == "__main__":
    sys.exit(main())
